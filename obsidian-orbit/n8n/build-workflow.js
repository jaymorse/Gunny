'use strict';

/**
 * Generate n8n/orbit-sync.workflow.json from ../lib and ../config.json.
 *
 * n8n Code nodes cannot require local files, so the library has to be inlined.
 * Generating it here means the code running in n8n is byte-for-byte the code
 * covered by ../test — no copy-paste drift between the tested logic and the
 * deployed logic. Re-run `npm run build` after touching anything in lib/.
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const LIB_FILES = ['frontmatter.js', 'normalize-markdown.js', 'build-payload.js'];

/** Strip module scaffolding so the files can share one scope. */
function inlineLib() {
  return LIB_FILES.map((file) => {
    const source = fs.readFileSync(path.join(ROOT, 'lib', file), 'utf8');
    const stripped = source
      .split('\n')
      .filter((line) => !/^'use strict';$/.test(line.trim()))
      .filter((line) => !/^(const|let|var)\s+\{?[\w\s,}]*\}?\s*=\s*require\(/.test(line.trim()))
      .filter((line) => !/^module\.exports\s*=/.test(line.trim()))
      .join('\n');
    return `// ---- lib/${file} ----\n${stripped.trim()}`;
  }).join('\n\n');
}

function loadConfig() {
  const local = path.join(ROOT, 'config.json');
  const example = path.join(ROOT, 'config.example.json');
  const source = fs.existsSync(local) ? local : example;
  const config = JSON.parse(fs.readFileSync(source, 'utf8'));
  delete config._comment;
  return { config, source: path.basename(source) };
}

function prepareCode(lib, config) {
  return `// GENERATED by n8n/build-workflow.js — edit lib/*.js and re-run \`npm run build\`.
// Config below is baked in at build time; edit config.json and rebuild, or
// tweak it here in the n8n UI for a quick experiment.
const CONFIG = ${JSON.stringify(config, null, 2)};

${lib}

// Accepts { notes: [{ path, content }] } — the shape both the Obsidian
// sender and the GitHub Action post. A single { path, content } also works.
const body = $input.first().json.body ?? $input.first().json;
const notes = Array.isArray(body.notes) ? body.notes : [body];

const out = [];
for (const note of notes) {
  if (!note || typeof note.content !== 'string') {
    out.push({ json: { ok: false, path: note?.path ?? '(unknown)', errors: ['No content supplied.'], warnings: [], skipped: null } });
    continue;
  }
  // currentColumn is unknown here; the column guard falls back to "only move
  // into owned columns". Fetch the card first if you want full rewind
  // protection on updates — see README.
  const result = buildPayload({ path: note.path, content: note.content, config: CONFIG });
  out.push({
    json: {
      ok: result.ok,
      skipped: result.skipped ?? null,
      errors: result.errors,
      warnings: result.warnings,
      action: result.action,
      cardId: result.cardId,
      hash: result.hash,
      payload: result.payload,
      path: note.path,
      originalContent: note.content,
      tags: result.tags,
    },
  });
}
return out;`;
}

function writeBackCode(lib, config) {
  return `// GENERATED by n8n/build-workflow.js — edit lib/*.js and re-run \`npm run build\`.
const CONFIG = ${JSON.stringify(config, null, 2)};

${lib}

// Read the created/updated card id out of the API response. Adjust
// response_card_id_path in config.json once you know the real shape.
function pick(object, dottedPath) {
  return String(dottedPath).split('.').reduce((node, key) => (node == null ? undefined : node[key]), object);
}

const responses = $input.all();
// HTTP Request emits one item per input item, in order, so pairing by index
// is safe here.
const built = $('Prepare payloads').all().filter((item) => item.json.ok);

const out = [];
responses.forEach((response, index) => {
  const source = built[index];
  if (!source) return;

  const idPath = CONFIG.response_card_id_path || 'id';
  const cardId = pick(response.json, idPath) ?? source.json.cardId;
  if (!cardId) {
    throw new Error(
      \`No card id at "\${idPath}" in the Orbit response for \${source.json.path}. \` +
      'Set response_card_id_path in config.json to match the real response.',
    );
  }

  const content = updateFrontmatter(source.json.originalContent, {
    orbit_card_id: cardId,
    orbit_synced_hash: source.json.hash,
  });

  out.push({ json: { path: source.json.path, content, cardId, action: source.json.action } });
});
return out;`;
}

function buildWorkflow() {
  const lib = inlineLib();
  const { config, source } = loadConfig();
  const api = config.api ?? {};
  const base = api.base_url ?? '';

  const createUrl = `${base}${api.create_path ?? '/cards'}`;
  const updateUrl = `${base}${api.update_path ?? '/cards/{cardId}'}`;
  // One HTTP node for both verbs keeps items aligned 1:1 with their notes.
  const urlExpression =
    `={{ $json.action === 'create' ? '${createUrl}' : '${updateUrl}'.replace('{cardId}', $json.cardId) }}`;
  const methodExpression =
    `={{ $json.action === 'create' ? 'POST' : '${api.update_method ?? 'PATCH'}' }}`;

  const nodes = [
    {
      parameters: {
        httpMethod: 'POST',
        path: 'orbit-sync',
        responseMode: 'responseNode',
        options: {},
      },
      id: 'webhook-vault-sync',
      name: 'Vault sync',
      type: 'n8n-nodes-base.webhook',
      typeVersion: 2,
      position: [-220, 300],
      webhookId: 'orbit-sync',
    },
    {
      parameters: { jsCode: prepareCode(lib, config), mode: 'runOnceForAllItems' },
      id: 'code-prepare-payloads',
      name: 'Prepare payloads',
      type: 'n8n-nodes-base.code',
      typeVersion: 2,
      position: [0, 300],
    },
    {
      parameters: { respondWith: 'allIncomingItems', options: {} },
      id: 'respond-report',
      name: 'Report back to vault',
      type: 'n8n-nodes-base.respondToWebhook',
      typeVersion: 1,
      position: [220, 300],
    },
    {
      parameters: {
        conditions: {
          options: { caseSensitive: true, leftValue: '', typeValidation: 'loose', version: 2 },
          conditions: [
            {
              id: 'is-ready',
              leftValue: '={{ $json.ok }}',
              rightValue: '',
              operator: { type: 'boolean', operation: 'true', singleValue: true },
            },
          ],
          combinator: 'and',
        },
        looseTypeValidation: true,
        options: {},
      },
      id: 'if-ready',
      name: 'Ready to sync?',
      type: 'n8n-nodes-base.if',
      typeVersion: 2.2,
      position: [440, 300],
    },
    {
      parameters: {
        method: methodExpression,
        url: urlExpression,
        sendHeaders: true,
        headerParameters: {
          parameters: [
            {
              name: api.auth_header ?? 'Authorization',
              value: `=${api.auth_prefix ?? 'Bearer '}{{ $env.ORBIT_TOKEN }}`,
            },
          ],
        },
        sendBody: true,
        specifyBody: 'json',
        jsonBody: '={{ JSON.stringify($json.payload) }}',
        options: { response: { response: { neverError: false } } },
      },
      id: 'http-orbit-card',
      name: 'Create or update card',
      type: 'n8n-nodes-base.httpRequest',
      typeVersion: 4.2,
      position: [680, 200],
    },
    {
      parameters: { jsCode: writeBackCode(lib, config), mode: 'runOnceForAllItems' },
      id: 'code-write-back',
      name: 'Stamp card id',
      type: 'n8n-nodes-base.code',
      typeVersion: 2,
      position: [900, 200],
    },
    {
      parameters: {
        method: 'PUT',
        url: `=${config.obsidian_rest_url ?? 'https://127.0.0.1:27124'}/vault/{{ encodeURIComponent($json.path) }}`,
        sendHeaders: true,
        headerParameters: {
          parameters: [
            { name: 'Authorization', value: '=Bearer {{ $env.OBSIDIAN_TOKEN }}' },
            { name: 'Content-Type', value: 'text/markdown' },
          ],
        },
        sendBody: true,
        contentType: 'raw',
        rawContentType: 'text/markdown',
        body: '={{ $json.content }}',
        // The Local REST API plugin serves a self-signed certificate.
        options: { allowUnauthorizedCerts: true },
      },
      id: 'http-vault-writeback',
      name: 'Write id back to vault',
      type: 'n8n-nodes-base.httpRequest',
      typeVersion: 4.2,
      position: [1120, 200],
    },
    {
      parameters: {},
      id: 'noop-skipped',
      name: 'Skipped or invalid',
      type: 'n8n-nodes-base.noOp',
      typeVersion: 1,
      position: [680, 420],
    },
  ];

  const connections = {
    'Vault sync': { main: [[{ node: 'Prepare payloads', type: 'main', index: 0 }]] },
    'Prepare payloads': { main: [[{ node: 'Report back to vault', type: 'main', index: 0 }]] },
    'Report back to vault': { main: [[{ node: 'Ready to sync?', type: 'main', index: 0 }]] },
    'Ready to sync?': {
      main: [
        [{ node: 'Create or update card', type: 'main', index: 0 }],
        [{ node: 'Skipped or invalid', type: 'main', index: 0 }],
      ],
    },
    'Create or update card': { main: [[{ node: 'Stamp card id', type: 'main', index: 0 }]] },
    'Stamp card id': { main: [[{ node: 'Write id back to vault', type: 'main', index: 0 }]] },
  };

  return {
    name: 'Obsidian → Orbit sync',
    nodes,
    connections,
    settings: { executionOrder: 'v1' },
    meta: { generatedBy: 'obsidian-orbit/n8n/build-workflow.js', configSource: source },
    pinData: {},
  };
}

if (require.main === module) {
  const workflow = buildWorkflow();
  const target = path.join(__dirname, 'orbit-sync.workflow.json');
  fs.writeFileSync(target, `${JSON.stringify(workflow, null, 2)}\n`);
  const nodeCount = workflow.nodes.length;
  process.stdout.write(
    `Wrote ${path.relative(ROOT, target)} (${nodeCount} nodes, config: ${workflow.meta.configSource})\n`,
  );
}

module.exports = { buildWorkflow, inlineLib };
